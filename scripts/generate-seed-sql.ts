/**
 * Writes supabase/seed.sql from buildSeed() — the same rows the demo backend uses.
 *
 *   pnpm db:seed-sql
 *
 * Dates in buildSeed() are relative to "now"; here they are pinned to SEED_NOW so
 * the file is deterministic (CI checks it is in sync). Regenerate to refresh.
 */
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildSeed } from "../src/lib/data/seed";
import type { Dataset } from "../src/lib/data/memory-store";
import type { TableName } from "../src/lib/domain/types";

export const SEED_NOW = new Date("2026-10-12T15:00:00Z");

